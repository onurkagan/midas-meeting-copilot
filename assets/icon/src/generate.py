"""Writes the Midas app icon (assets/icon/Midas.svg), in the Tide style.

King Midas's donkey ears rising from his crown, drawn as two leaves in white on a tile of
sea blue to seafoam, with a soft swell along the bottom. The tile follows Apple's macOS
icon grid: an 824 pt continuous-corner body on a 1024 pt canvas, with the standard shadow.

The ears and crown are the same curves as the menu bar glyph (native/Overlay/Art.swift),
drawn in a 100-unit box.
"""

import sys

from squircle import squircle

BODY = squircle(100, 100, 824, 824, 185.4)

# The mark, in its 100-unit box.
LEFT_EAR = "M44 62 C33 50 29 28 34 12 C45 22 50 40 48 60 Z"
RIGHT_EAR = "M56 62 C67 50 71 28 66 12 C55 22 50 40 52 60 Z"
LEFT_VEIN = "M45.5 58 C42 45 38.5 31 35.5 17"
RIGHT_VEIN = "M54.5 58 C58 45 61.5 31 64.5 17"
CROWN = "M28 84 L31 66 L40 74 L50 62 L60 74 L69 66 L72 84 Z"
# Fits the mark's 44 x 72 units into the tile, a little above the middle.
MARK = "translate(232 214) scale(5.6)"

SVG = f"""<!-- Midas app icon (1024 x 1024 master), Tide style. Generated by assets/icon/src/generate.py. -->
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <defs>
    <linearGradient id="sea" gradientUnits="userSpaceOnUse" x1="100" y1="100" x2="924" y2="924">
      <stop offset="0" stop-color="#1F6FB8"/>
      <stop offset="0.55" stop-color="#2A8FB6"/>
      <stop offset="1" stop-color="#3BB3A6"/>
    </linearGradient>
    <linearGradient id="sheen" gradientUnits="userSpaceOnUse" x1="0" y1="100" x2="0" y2="560">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.30"/>
      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="leaf" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#FFFFFF"/>
      <stop offset="1" stop-color="#E2F3F8"/>
    </linearGradient>
    <clipPath id="tile"><path d="{BODY}"/></clipPath>
    <filter id="drop" x="-10%" y="-10%" width="120%" height="125%">
      <feDropShadow dx="0" dy="12" stdDeviation="14" flood-color="#0B2F4A" flood-opacity="0.32"/>
    </filter>
    <filter id="lift" x="-30%" y="-20%" width="160%" height="150%">
      <feDropShadow dx="0" dy="10" stdDeviation="12" flood-color="#0B3A5C" flood-opacity="0.28"/>
    </filter>
  </defs>
  <g filter="url(#drop)"><path d="{BODY}" fill="url(#sea)"/></g>
  <g clip-path="url(#tile)">
    <path d="M100 742 C230 700 330 798 512 748 C694 698 794 796 924 750 L924 924 L100 924 Z" fill="#FFFFFF" fill-opacity="0.15"/>
    <path d="M100 818 C250 778 360 870 512 826 C664 782 784 866 924 824 L924 924 L100 924 Z" fill="#FFFFFF" fill-opacity="0.12"/>
    <rect x="100" y="100" width="824" height="460" fill="url(#sheen)"/>
    <path d="{BODY}" fill="none" stroke="#FFFFFF" stroke-opacity="0.22" stroke-width="4"/>
  </g>
  <g filter="url(#lift)">
    <g transform="{MARK}">
      <path d="{LEFT_EAR}" fill="url(#leaf)"/>
      <path d="{RIGHT_EAR}" fill="url(#leaf)"/>
      <path d="{LEFT_VEIN}" fill="none" stroke="#8FCDE3" stroke-width="1.7" stroke-linecap="round"/>
      <path d="{RIGHT_VEIN}" fill="none" stroke="#8FCDE3" stroke-width="1.7" stroke-linecap="round"/>
      <path d="{CROWN}" fill="#FFFFFF" stroke="#FFFFFF" stroke-width="2.4" stroke-linejoin="round"/>
    </g>
  </g>
</svg>
"""

if __name__ == "__main__":
    with open(sys.argv[1], "w", encoding="utf-8") as handle:
        handle.write(SVG)
